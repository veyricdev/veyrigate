import { Inject, Injectable, Optional } from '@nestjs/common';
import { generateToken } from '../../../common/crypto/crypto.util';
import { loadLuaScripts } from '../../../database/redis/lua-loader';
import { RedisService } from '../../../database/redis/redis.service';

/** DI token for an injectable clock (ms epoch). Tests use it to jump past the TTL. */
export const AUTHZ_CTX_CLOCK = 'AUTHZ_CTX_CLOCK';

/** TTL of an AuthorizeRequestContext (spec §9.1: 5–10 min). Fixed at 10 min; set once, never slid. */
export const CONTEXT_TTL_MS = 10 * 60 * 1000;

/**
 * DEBT-413: browser-binding cookie of a `login` context (`__Host-idp_authz` when Secure). One value
 * per browser, reused (never rotated) so several tabs do not break each other; `Max-Age` =
 * `CONTEXT_TTL_MS`. Only its sha256 is stored (`AuthorizeRequestContext.bindingHash`).
 */
export const AUTHZ_BINDING_COOKIE = 'idp_authz';

/**
 * Persisted context of an in-flight `/authorize` request (spec §9.1).
 *
 * `originalState`/`nonce` are the RP's values, kept only to echo back at the final redirect —
 * they are NOT used as the lookup key. The lookup key is `request_id`, generated by the IdP and
 * independent of the RP's `state` (spec §9.1, tech-lead C8).
 */
export interface AuthorizeRequestContext {
  /**
   * Which door may consume this context (run 26 retry, DEBT-122): `login` only via the resume
   * `/authorize?request_id=`, `consent` only via `POST /authorize/consent`. A context missing the
   * field (or of the other kind) is refused by both doors (fail-closed).
   */
  kind: 'login' | 'consent';
  clientId: string;
  redirectUri: string;
  codeChallenge: string;
  scope: string;
  resource?: string;
  originalState?: string;
  nonce?: string;
  /**
   * B6.2: ms epoch at which re-authentication was demanded (`prompt=login` or `max_age` exceeded,
   * incl. `max_age=0`). Present ONLY on such contexts: `GET /login` then shows the form even to a
   * live session, and the resume refuses (`login_required`) unless the session authenticated at or
   * after this instant.
   */
  reauthAfter?: number;
  /**
   * DEBT-123: `Session.ref` of the session that opened the consent screen (`consent` contexts only).
   * `POST /authorize/consent` refuses any other session (and a context without it). Server-side
   * only: never rendered, logged, audited or put in a URL.
   */
  sessionRef?: string;
  /**
   * DEBT-413: sha256 of the `idp_authz` cookie of the browser that created the context (`login`
   * contexts only). The resume refuses any other browser (and a context without it). Server-side
   * only: never rendered, logged, audited or put in a URL.
   */
  bindingHash?: string;
  createdAt: number;
  expiresAt: number;
}

const ctxKey = (requestId: string): string => `authz_ctx:${requestId}`;

/**
 * Atomic single-use read: return the value and delete the key in one round trip, so two
 * concurrent resumes of the same `request_id` can never both succeed (tech-lead C3). A plain
 * GET+DEL would race between the two commands.
 */
const CONSUME_SCRIPT = {
  name: 'authzCtxConsume',
  numberOfKeys: 1,
  lua: `
local v = redis.call('GET', KEYS[1])
if v then redis.call('DEL', KEYS[1]) end
return v`,
};

/**
 * DEBT-413: the resume door. A `login` context is returned and deleted only when the caller's
 * binding hash equals the stored one; otherwise nil and the key is KEPT, so a holder of the URL
 * cannot burn the victim's context (compare-before-DEL, like `consumeAuthCode`, INV-13). A context
 * of another kind is consumed as before (DEBT-122: the caller then refuses it).
 */
const CONSUME_LOGIN_SCRIPT = {
  name: 'authzCtxConsumeLogin',
  numberOfKeys: 1,
  lua: `
local v = redis.call('GET', KEYS[1])
if not v then return nil end
local d = cjson.decode(v)
if d.kind == 'login' and (ARGV[1] == '' or d.bindingHash ~= ARGV[1]) then return nil end
redis.call('DEL', KEYS[1])
return v`,
};

type AuthzRedis = {
  authzCtxConsume(key: string): Promise<string | null>;
  authzCtxConsumeLogin(key: string, bindingHash: string): Promise<string | null>;
};

/**
 * AuthorizeRequestContext store on Redis (B4.1, spec §9.1).
 *
 * - `create` mints an opaque `request_id` (CSPRNG) decoupled from the RP's `state`, sets the
 *   context with a fixed TTL (no sliding), and returns the id.
 * - `consume` is atomic single-use: the context is deleted the moment it is read.
 */
@Injectable()
export class AuthorizeRequestContextService {
  private readonly now: () => number;

  constructor(
    private readonly redis: RedisService,
    @Optional() @Inject(AUTHZ_CTX_CLOCK) now?: () => number,
  ) {
    this.now = now ?? Date.now;
    loadLuaScripts(redis.client, [CONSUME_SCRIPT, CONSUME_LOGIN_SCRIPT]);
  }

  async create(
    data: Omit<AuthorizeRequestContext, 'createdAt' | 'expiresAt'>,
  ): Promise<{ requestId: string; context: AuthorizeRequestContext }> {
    const requestId = generateToken();
    const createdAt = this.now();
    const context: AuthorizeRequestContext = {
      ...data,
      createdAt,
      expiresAt: createdAt + CONTEXT_TTL_MS,
    };
    // PX + NX: set with the TTL atomically; NX guards against the astronomically unlikely id reuse.
    const ok = await this.redis.client.set(
      ctxKey(requestId),
      JSON.stringify(context),
      'PX',
      CONTEXT_TTL_MS,
      'NX',
    );
    if (ok !== 'OK') {
      throw new Error('AuthorizeRequestContext id collision');
    }
    return { requestId, context };
  }

  /** Read-and-delete the context. Returns null when missing/expired/already consumed. */
  async consume(requestId: string): Promise<AuthorizeRequestContext | null> {
    if (!requestId) return null;
    const raw = await (this.redis.client as unknown as AuthzRedis).authzCtxConsume(
      ctxKey(requestId),
    );
    return raw ? (JSON.parse(raw) as AuthorizeRequestContext) : null;
  }

  /**
   * Resume door (DEBT-413): like `consume`, but a `login` context is consumed only when
   * `bindingHash` matches the stored one (atomic, compared before the DEL). A missing hash never
   * matches, so a resume without the cookie, or of a context created before DEBT-413, is refused.
   */
  async consumeForResume(
    requestId: string,
    bindingHash: string | undefined,
  ): Promise<AuthorizeRequestContext | null> {
    if (!requestId) return null;
    const raw = await (this.redis.client as unknown as AuthzRedis).authzCtxConsumeLogin(
      ctxKey(requestId),
      bindingHash ?? '',
    );
    return raw ? (JSON.parse(raw) as AuthorizeRequestContext) : null;
  }

  /**
   * Non-consuming read (DEBT-084): plain `GET`, never `DEL`, never touches the TTL (INV-084-3). Used
   * only to derive the registered `redirectUri` origin for the per-response CSP `form-action` on
   * `GET /login`; the single-use `consume` on the resumed `/authorize` is unaffected.
   */
  async peek(requestId: string): Promise<AuthorizeRequestContext | null> {
    if (!requestId) return null;
    const raw = await this.redis.client.get(ctxKey(requestId));
    return raw ? (JSON.parse(raw) as AuthorizeRequestContext) : null;
  }
}
