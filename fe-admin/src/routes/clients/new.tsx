import { useState } from "react";
import { createFileRoute, useNavigate } from "@tanstack/react-router";
import { toast } from "sonner";
import { failureMessage } from "@/components/feedback/form-feedback";
import { ClientForm } from "@/features/clients/client-form";
import {
  EMPTY_VALUES,
  METHODS_FOR,
  NewClientDraftSchema,
  toCreateBody,
  type AuthMethod,
  type ClientType,
  type NewClientDraft,
} from "@/features/clients/client-form-schema";
import { useCreateClient, useResources } from "@/features/admin-api/hooks";
import { startStepUp, useStepUpDraft } from "@/features/admin-api/step-up";
import { AdminRequestError } from "@/features/admin-api/types";

export const Route = createFileRoute("/clients/new")({ component: NewClientPage });

const ACTION = "client.create";
const PATH = "/clients/new";

const TYPE_LABELS: Record<ClientType, string> = {
  confidential: "Confidential (server-side app with a secret)",
  public: "Public (browser or native app, no secret)",
};

function NewClientPage() {
  const { viewer } = Route.useRouteContext();
  const draft = useStepUpDraft(NewClientDraftSchema, ACTION, PATH, viewer.sub);
  return (
    <section aria-labelledby="new-client-title" className="space-y-6">
      <h1 id="new-client-title" className="text-2xl font-semibold">
        New client
      </h1>
      <p className="text-sm text-muted-foreground">The client ID is generated by the server. Secrets are managed after creation.</p>
      <NewClientForm key={draft ? "restored" : "blank"} draft={draft} sub={viewer.sub} />
    </section>
  );
}

function NewClientForm({ draft, sub }: { draft: NewClientDraft | null; sub: string }) {
  const navigate = useNavigate();
  const create = useCreateClient();
  const resources = useResources();
  const { clientType: draftType, tokenEndpointAuthMethod: draftMethod, ...initial } = draft ?? {
    ...EMPTY_VALUES,
    clientType: "confidential" as const,
    tokenEndpointAuthMethod: "client_secret_basic" as const,
  };
  const [type, setType] = useState<ClientType>(draftType);
  const [method, setMethod] = useState<AuthMethod>(
    METHODS_FOR[draftType].includes(draftMethod) ? draftMethod : METHODS_FOR[draftType][0]!,
  );

  return (
    <ClientForm
      initial={initial}
      restored={draft !== null}
      resources={{ options: resources.data, failed: resources.isError }}
      submitLabel="Create client"
      onSubmit={async (fields, values) => {
        try {
          const created = await create.mutateAsync(toCreateBody(type, method, fields));
          toast.success("Client created.");
          void navigate({ to: "/clients/$clientId", params: { clientId: created.clientId } });
          return null;
        } catch (err) {
          if (err instanceof AdminRequestError && err.code === "step_up_required") {
            const payload = { ...values, clientType: type, tokenEndpointAuthMethod: method };
            startStepUp(NewClientDraftSchema, { action: ACTION, path: PATH, sub, payload });
            return { info: "Confirm your identity to continue…" };
          }
          const message = failureMessage(
            err,
            "The client may have been created. Check the client list before trying again.",
          );
          return message ? { error: message } : null;
        }
      }}
    >
      <fieldset className="space-y-2">
        <legend className="text-sm font-medium">Client type</legend>
        {(Object.keys(TYPE_LABELS) as ClientType[]).map((t) => (
          <label key={t} className="flex items-center gap-2 text-sm">
            <input
              type="radio"
              name="clientType"
              className="size-4"
              checked={type === t}
              onChange={() => {
                setType(t);
                setMethod(METHODS_FOR[t][0]!); // a type change resets the method to a valid one
              }}
            />
            {TYPE_LABELS[t]}
          </label>
        ))}
      </fieldset>
      <fieldset className="space-y-2">
        <legend className="text-sm font-medium">Token endpoint auth method</legend>
        {METHODS_FOR[type].map((m) => (
          <label key={m} className="flex items-center gap-2 text-sm">
            <input
              type="radio"
              name="tokenEndpointAuthMethod"
              className="size-4"
              checked={method === m}
              onChange={() => setMethod(m)}
            />
            <span className="font-mono">{m}</span>
          </label>
        ))}
      </fieldset>
    </ClientForm>
  );
}
